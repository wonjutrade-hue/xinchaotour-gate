export function getProductFallbackImage(category?: string, city?: string): string {
  // 1. POOL VILLA MUST ALWAYS HAVE REAL POOL VILLA PHOTO
  if (category === '풀빌라') {
    if (city?.includes('다낭')) return '/images/villa_danang_mykhe_6bed.jpg';
    if (city?.includes('도심') || city?.includes('시티') || city?.includes('대저택')) return '/images/vietnam_city_villa.jpg';
    return '/images/vietnam_beach_villa.jpg';
  }

  // 2. GOLF TOUR MUST ALWAYS HAVE REAL GOLF PHOTO
  if (category === '골프투어') {
    if (city?.includes('호이안')) return '/images/golf_hoiana_shores.jpg';
    return '/images/vietnam_golf_resort.jpg';
  }

  // 3. City-specific scenic spots for packages and free tours
  if (city) {
    if (city.includes('나트랑')) return '/images/nhatrang_bay.jpg';
    if (city.includes('달랏')) return '/images/dalat.jpg';
    if (city.includes('다낭')) return '/images/danang_city_dragon.jpg';
    if (city.includes('호이안')) return '/images/hoian_lantern.jpg';
    if (city.includes('푸꾸옥')) return '/images/phuquoc_sunset.jpg';
    if (city.includes('사파')) return '/images/sapa_fansipan.jpg';
    if (city.includes('하노이') || city.includes('하롱')) return '/images/halong_cruise.jpg';
    if (city.includes('닌빈')) return '/images/ninhbinh_trangan.jpg';
    if (city.includes('무이네')) return '/images/muine_sand.jpg';
    if (city.includes('후에')) return '/images/hue_imperial_citadel.jpg';
    if (city.includes('판랑')) return '/images/phanrang_desert_jeep.jpg';
    if (city.includes('호치민')) return '/images/mekong_river_boat.jpg';
  }
  return '/images/danang_golden_bridge.jpg';
}

export function getDisplayProductImage(product?: { id?: string; imageUrl?: string; additionalImages?: string[]; category?: string; city?: string; title?: string; subTitle?: string } | null): string {
  if (!product) return DEFAULT_TRAVEL_FALLBACK;

  // 1. Clean custom user-uploaded or specified imageUrl takes top priority!
  if (
    product.imageUrl && 
    typeof product.imageUrl === 'string' &&
    product.imageUrl.trim().length > 0 && 
    product.imageUrl !== 'VILLA_PHOTO_DATA' && 
    product.imageUrl !== 'TEST_IMG'
  ) {
    return product.imageUrl.trim();
  }

  // 2. If additional gallery images exist, check for first valid image
  if (Array.isArray(product.additionalImages)) {
    const firstValid = product.additionalImages.find(
      img => img && typeof img === 'string' && img.trim().length > 0 && 
             img !== 'VILLA_PHOTO_DATA' && img !== 'TEST_IMG'
    );
    if (firstValid) return firstValid.trim();
  }

  // 3. Fallback to DIRECT PRODUCT ID 1:1 UNIQUE PHOTO GUARANTEE if available
  const id = product.id || '';
  if (id && MASTER_UNIQUE_PRODUCT_IMAGES[id]) {
    return MASTER_UNIQUE_PRODUCT_IMAGES[id];
  }

  // 4. City & Category scenic spots fallback
  return getProductFallbackImage(product.category, product.city);
}

